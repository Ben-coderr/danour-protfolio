export function getLocalizedProject(project: Project, locale: Locale): Project {
  if (locale === 'en') return project;

  const ar = projectsAr[project.slug];
  if (!ar) return project;

  return {
    ...project,
    title: ar.title || project.title,
    category: ar.category || project.category,
    summary: ar.summary || project.summary,
    fullDescription: ar.fullDescription || project.fullDescription,
    challenge: ar.challenge || project.challenge,
    solution: ar.solution || project.solution,
    role: ar.role || project.role,
    bullets: ar.bullets || project.bullets,
    metrics: ar.metrics || project.metrics,
    architecturalDecisions: ar.architecturalDecisions || project.architecturalDecisions,
  };
}
